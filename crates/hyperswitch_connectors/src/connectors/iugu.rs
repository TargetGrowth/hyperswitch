impl ConnectorIntegration<Authorize, PaymentsAuthorizeData, PaymentsResponseData> for Iugu {
    fn get_headers(
        &self,
        req: &PaymentsAuthorizeRouterData,
        connectors: &Connectors,
    ) -> CustomResult<Vec<(String, masking::Maskable<String>)>, errors::ConnectorError> {
        self.build_headers(req, connectors)
    }

    fn get_content_type(&self) -> &'static str {
        self.common_get_content_type()
    }

    fn get_url(
        &self,
        req: &PaymentsAuthorizeRouterData,
        connectors: &Connectors,
    ) -> CustomResult<String, errors::ConnectorError> {
        use hyperswitch_domain_models::payment_method_data::PaymentMethodData;
        let base = self.base_url(connectors);
        match &req.request.payment_method_data {
            PaymentMethodData::Card(_) => Ok(format!("{}/charge", base)),
            PaymentMethodData::BankRedirect(_) | PaymentMethodData::BankTransfer(_) | PaymentMethodData::Wallet(_) => Ok(format!("{}/invoices", base)),
            _ => Err(errors::ConnectorError::NotImplemented("Payment method not supported".to_string()).into()),
        }
    }

    fn get_request_body(
        &self,
        req: &PaymentsAuthorizeRouterData,
        _connectors: &Connectors,
    ) -> CustomResult<RequestContent, errors::ConnectorError> {
        use hyperswitch_domain_models::payment_method_data::PaymentMethodData;
        match &req.request.payment_method_data {
            PaymentMethodData::Card(_) => {
                let connector_req = IuguChargeRequest::try_from(req)?;
                Ok(RequestContent::Json(Box::new(connector_req)))
            }
            PaymentMethodData::BankRedirect(_) | PaymentMethodData::BankTransfer(_) | PaymentMethodData::Wallet(_) => {
                let connector_req = IuguInvoiceRequest::try_from(req)?;
                Ok(RequestContent::Json(Box::new(connector_req)))
            }
            _ => Err(errors::ConnectorError::NotImplemented("Payment method not supported".to_string()).into()),
        }
    }

    fn build_request(
        &self,
        req: &PaymentsAuthorizeRouterData,
        connectors: &Connectors,
    ) -> CustomResult<Option<Request>, errors::ConnectorError> {
        Ok(Some(
            RequestBuilder::new()
                .method(Method::Post)
                .url(&types::PaymentsAuthorizeType::get_url(
                    self, req, connectors,
                )?)
                .attach_default_headers()
                .headers(types::PaymentsAuthorizeType::get_headers(
                    self, req, connectors,
                )?)
                .set_body(types::PaymentsAuthorizeType::get_request_body(
                    self, req, connectors,
                )?)
                .build(),
        ))
    }

    fn handle_response(
        &self,
        data: &PaymentsAuthorizeRouterData,
        event_builder: Option<&mut ConnectorEvent>,
        res: Response,
    ) -> CustomResult<PaymentsAuthorizeRouterData, errors::ConnectorError> {
        let response: IuguInvoiceResponse = res
            .response
            .parse_struct("Iugu PaymentsAuthorizeResponse")
            .change_context(errors::ConnectorError::ResponseDeserializationFailed)?;
        event_builder.map(|i| i.set_response_body(&response));
        router_env::logger::info!(connector_response=?response);
        
        let status = AttemptStatus::from(response.status.clone());
        let resource_id = ResponseId::ConnectorTransactionId(response.id.clone());
        let redirection_data = response.secure_url.as_ref().map(|url| {
            Box::new(Some(RedirectForm::from((url::Url::parse(url).unwrap(), Method::Get))))
        }).unwrap_or(Box::new(None));
        let payments_response = PaymentsResponseData::TransactionResponse {
            resource_id,
            redirection_data,
            mandate_reference: Box::new(None),
            connector_metadata: None,
            network_txn_id: None,
            connector_response_reference_id: None,
            incremental_authorization_allowed: None,
            charges: None,
        };
        Ok(RouterData {
            response: Ok(payments_response),
            status,
            ..data.clone()
        })
    }

    fn get_error_response(
        &self,
        res: Response,
        event_builder: Option<&mut ConnectorEvent>,
    ) -> CustomResult<ErrorResponse, errors::ConnectorError> {
        self.build_error_response(res, event_builder)
    }
}

